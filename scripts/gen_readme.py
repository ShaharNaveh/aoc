"""Generate the top-level README.md with a per-year table of solved days.

Usage (from anywhere):

    python3 scripts/gen_readme.py
"""

import collections
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent

# Language name -> glob (relative to ROOT) matching one file per solved day.
LANGUAGES = {
    "Python": "python/year*/day*.py",
    "Rust": "rust/crates/year*/src/bin/day*.rs",
}

PATH_RE = re.compile(r"year(\d{4}).*day(\d{2})")


def days_in(year: int) -> int:
    # Advent of Code shrank to 12 days starting in 2025.
    return 12 if year >= 2025 else 25


def find_solutions() -> dict[int, dict[int, dict[str, pathlib.Path]]]:
    """Return {year: {day: {language: path}}}."""
    solutions = collections.defaultdict(lambda: collections.defaultdict(dict))
    for lang, pattern in LANGUAGES.items():
        for path in ROOT.glob(pattern):
            m = PATH_RE.search(path.relative_to(ROOT).as_posix())
            if m is None:
                continue
            year, day = map(int, m.groups())
            solutions[year][day][lang] = path.relative_to(ROOT)
    return solutions


def render(solutions: dict[int, dict[int, dict[str, pathlib.Path]]]) -> str:
    langs = list(LANGUAGES)
    lines = [
        "# Advent of Code",
        "",
        "Solutions to [Advent of Code](https://adventofcode.com) puzzles.",
        "",
        "<!-- Generated by scripts/gen_readme.py; do not edit by hand. -->",
    ]

    for year in sorted(solutions, reverse=True):
        days = solutions[year]
        total = days_in(year)
        lines += [
            "",
            f"## {year}",
            "",
            f"{len(days)}/{total} days solved.",
            "",
            "| Day | " + " | ".join(langs) + " |",
            "|---:|" + ":---:|" * len(langs),
        ]
        for day in range(1, total + 1):
            puzzle = f"[{day}](https://adventofcode.com/{year}/day/{day})"
            found = days.get(day, {})
            cells = [
                f"[✓]({found[lang].as_posix()})" if lang in found else ""
                for lang in langs
            ]
            lines.append(f"| {puzzle} | " + " | ".join(cells) + " |")

    return "\n".join(lines) + "\n"


def main() -> None:
    (ROOT / "README.md").write_text(render(find_solutions()))


if __name__ == "__main__":
    main()
